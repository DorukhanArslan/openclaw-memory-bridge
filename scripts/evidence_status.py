"""Inspect optional historical model inputs without executing providers or reports."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any, Iterable, Mapping


MODEL_INPUTS = (
    ("live-smoke/acceptance.json", ("MODEL-01",)),
    ("lifecycle-acceptance/acceptance.json", ("MODEL-02", "MODEL-03", "MODEL-04")),
    ("provenance-merge-acceptance/acceptance.json", ("MODEL-05", "MODEL-06")),
)


class EvidenceInputError(ValueError):
    """Required JSON inputs are missing, unreadable, or malformed."""


class MissingEvidenceError(FileNotFoundError):
    """An optional historical record is absent; callers choose skip or failure."""


def evidence_path(foundation: Path | str, relative: Path | str, *, evidence_root: Path | str | None = None) -> Path:
    """Resolve evidence/... beneath a supplied or configured evidence directory."""
    relative = Path(relative)
    if relative.is_absolute() or ".." in relative.parts:
        raise ValueError("Evidence paths must be relative and cannot contain '..'.")
    if relative.parts and relative.parts[0] == "evidence":
        relative = Path(*relative.parts[1:])
    root = evidence_root if evidence_root is not None else os.environ.get("BRIDGE_EVIDENCE_ROOT")
    return ((Path(root).expanduser() if root else Path(foundation) / "evidence") / relative).resolve()


def model_evidence_required(environ: Mapping[str, str] | None = None) -> bool:
    """Strict audit selection never authorizes or dispatches model requests."""
    value = (os.environ if environ is None else environ).get("BRIDGE_REQUIRE_MODEL_EVIDENCE", "")
    if value not in ("", "0", "1"):
        raise ValueError("BRIDGE_REQUIRE_MODEL_EVIDENCE must be 0 or 1.")
    return value == "1"


def inspect_json_input(path: Path | str, *, object_only: bool = False) -> tuple[str, Any]:
    """Return availability and parsed data; never expose data in status messages."""
    path = Path(path)
    try:
        text = path.read_text(encoding="utf8")
    except FileNotFoundError:
        return "missing", None
    except (OSError, UnicodeError):
        return "unreadable", None
    try:
        value = json.loads(text)
    except json.JSONDecodeError:
        return "invalid-json", None
    if not isinstance(value, dict if object_only else (dict, list)):
        return "invalid-shape", None
    return "available", value


def require_json_inputs(paths: Iterable[Path | str]) -> dict[Path, Any]:
    """Preflight every required object/list before a generator writes output."""
    records = {}
    problems = []
    for path in dict.fromkeys(Path(path) for path in paths):
        status, value = inspect_json_input(path)
        if status != "available":
            problems.append(f"  - {path}: {status}")
        else:
            records[path] = value
    if problems:
        raise EvidenceInputError(
            "Missing or invalid required JSON inputs:\n" + "\n".join(problems)
            + "\nSupply the preserved input records; no report was generated by this preflight."
        )
    return records


def load_record(foundation: Path | str, relative: Path | str, *, evidence_root: Path | str | None = None) -> dict[str, Any]:
    """Load a genuine historical record; absence is distinct from invalid data."""
    path = evidence_path(foundation, relative, evidence_root=evidence_root)
    status, value = inspect_json_input(path, object_only=True)
    if status == "missing":
        raise MissingEvidenceError(
            f"Historical model evidence is missing: {path}. "
            "Supply the preserved genuine record, or inspect availability with "
            "python3 scripts/evidence_status.py --json. Do not substitute a mock."
        )
    if status != "available":
        raise EvidenceInputError(f"Historical model evidence is {status}: {path}")
    return value


def evidence_status(foundation: Path | str, *, evidence_root: Path | str | None = None) -> dict[str, Any]:
    inputs = []
    for relative, cases in MODEL_INPUTS:
        path = evidence_path(foundation, relative, evidence_root=evidence_root)
        status, _ = inspect_json_input(path, object_only=True)
        inputs.append({"path": str(path), "cases": list(cases), "status": status})
    return {
        "kind": "historical-model-evidence-availability",
        "complete": all(item["status"] == "available" for item in inputs),
        "inputs": inputs,
        "unsupportedCases": ["MODEL-07"],
        "scope": "Availability and JSON shape only; not model acceptance or a new live run.",
        "modelCalls": 0,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--foundation", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--evidence-root", type=Path, help="Directory containing live-smoke/, lifecycle-acceptance/, and provenance-merge-acceptance/.")
    parser.add_argument("--require-complete", action="store_true", help="Exit nonzero if a MODEL-01 through MODEL-06 input is unavailable.")
    parser.add_argument("--json", action="store_true", help="Emit metadata only, never record payloads.")
    args = parser.parse_args(argv)
    status = evidence_status(args.foundation, evidence_root=args.evidence_root)
    if args.json:
        print(json.dumps(status, indent=2))
    else:
        for item in status["inputs"]:
            print(f"{','.join(item['cases'])}: {item['status']}: {item['path']}")
        print("MODEL-07: unsupported supersession; independent of missing historical inputs.")
        print(status["scope"])
    # An invalid supplied artifact is an error even in optional inventory mode.
    invalid = any(item["status"] not in ("available", "missing") for item in status["inputs"])
    return 1 if invalid or (args.require_complete and not status["complete"]) else 0


if __name__ == "__main__":
    raise SystemExit(main())
